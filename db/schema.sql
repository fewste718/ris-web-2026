-- ЛР9. Схема учебной БД управления заявками технической поддержки.
-- ВНИМАНИЕ: повторный запуск удаляет данные только этих четырёх таблиц.
-- Выполнять в отдельной учебной БД mobius_support_lab09, не в postgres.
BEGIN;

-- Сначала удаляем зависимые таблицы. CASCADE не используется.
DROP TABLE IF EXISTS support_tickets;
DROP TABLE IF EXISTS equipment;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS clients;

CREATE TABLE clients (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name text NOT NULL CHECK (btrim(name) <> '')
);

CREATE TABLE equipment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    name text NOT NULL CHECK (btrim(name) <> ''),
    client_id integer NOT NULL REFERENCES clients (id) ON DELETE RESTRICT
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    login text NOT NULL UNIQUE CHECK (btrim(login) <> ''),
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    role varchar(16) NOT NULL CHECK (role IN ('Dispatcher', 'Engineer')),
    password_hash text NOT NULL CHECK (btrim(password_hash) <> '')
);

CREATE TABLE support_tickets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    number varchar(32) NOT NULL UNIQUE CHECK (btrim(number) <> ''),
    title varchar(80) NOT NULL,
    description varchar(500) NOT NULL,
    equipment_id integer NOT NULL REFERENCES equipment (id) ON DELETE RESTRICT,
    status varchar(16) NOT NULL DEFAULT 'New',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    assignee_user_id integer REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT support_tickets_title_check
        CHECK (title = btrim(title) AND char_length(title) BETWEEN 5 AND 80),
    CONSTRAINT support_tickets_description_check
        CHECK (description = btrim(description) AND char_length(description) BETWEEN 10 AND 500),
    CONSTRAINT support_tickets_status_check
        CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled'))
);

-- Ускоряет выборку заявок по статусу: WHERE status = 'New'.
CREATE INDEX support_tickets_status_idx ON support_tickets (status);

-- Ускоряет поиск заявок по оборудованию и соединение по equipment_id.
CREATE INDEX support_tickets_equipment_id_idx ON support_tickets (equipment_id);

COMMIT;
